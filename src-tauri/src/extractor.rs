    let location = terms.first().cloned().filter(|value| !value.is_empty());
    let role = terms
        .last()
        .cloned()
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| "Software Engineer".into());
    let source_domain = Url::parse(url)
        .ok()
        .and_then(|url| url.host_str().map(str::to_string))
        .unwrap_or_else(|| "jobs.example.com".into());
